local TAG = "##SB##"
local frame = CreateFrame("Frame")

local scanTip = CreateFrame("GameTooltip", "StatBoostScanTip", nil, "GameTooltipTemplate")
scanTip:SetOwner(WorldFrame, "ANCHOR_NONE")

local firstSlotForText = {}
local needsRebuild = true

frame:RegisterEvent("PLAYER_EQUIPMENT_CHANGED")
frame:RegisterEvent("PLAYER_ENTERING_WORLD")
frame:SetScript("OnEvent", function()
    needsRebuild = true
end)

local function RebuildEquippedCache()
    wipe(firstSlotForText)
    for clientSlot = 1, 19 do
        local link = GetInventoryItemLink("player", clientSlot)
        if link then
            scanTip:ClearLines()
            scanTip:SetInventoryItem("player", clientSlot)
            for i = 1, scanTip:NumLines() do
                local line = _G["StatBoostScanTipTextLeft" .. i]
                if line then
                    local text = line:GetText()
                    if text and text:find(TAG, 1, true) then
                        local clean = text:gsub(TAG, "")
                        clean = clean:gsub("|c%x%x%x%x%x%x%x%x", "")
                        clean = clean:gsub("|r", "")
                        if not firstSlotForText[clean] then
                            firstSlotForText[clean] = clientSlot
                        end
                    end
                end
            end
        end
    end
    needsRebuild = false
end

local function IsItemEquippedAtSlot(itemLink)
    if not itemLink then return nil end
    for clientSlot = 1, 19 do
        local link = GetInventoryItemLink("player", clientSlot)
        if link and link == itemLink then
            return clientSlot
        end
    end
    return nil
end

