local function GetItemIdFromLink(itemLink)
    if not itemLink then return nil end
    local id = itemLink:match("item:(%d+)")
    return id and tonumber(id) or nil
end

GameTooltip:HookScript("OnTooltipSetItem", function(self)
    if needsRebuild then
        RebuildEquippedCache()
    end

    local _, itemLink = self:GetItem()
    local itemId = GetItemIdFromLink(itemLink)
    if not itemId then return end


    -- Boosted item tooltip: recolor ##SB## lines
    local equippedSlot = IsItemEquippedAtSlot(itemLink)

    for i = 1, self:NumLines() do
        local line = _G["GameTooltipTextLeft" .. i]
        if line then
            local text = line:GetText()
            if text and text:find(TAG, 1, true) then
                local clean = text:gsub(TAG, "")
                clean = clean:gsub("|c%x%x%x%x%x%x%x%x", "")
                clean = clean:gsub("|r", "")

                local isDuplicate = false
                local firstSlot = firstSlotForText[clean]

                if equippedSlot then
                    isDuplicate = firstSlot ~= nil and firstSlot ~= equippedSlot
                else
                    isDuplicate = firstSlot ~= nil
                end

                if isDuplicate then
                    line:SetText("|cff888888" .. clean .. " (\208\180\209\131\208\177\208\187\208\184\209\128\209\131\208\181\209\130\209\129\209\143)|r")
                else
                    line:SetText("|cffffff00" .. clean .. "|r")
                end
            end
        end
    end
end)
